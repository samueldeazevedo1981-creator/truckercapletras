import assert from 'node:assert/strict';
import {DEFAULT_PEDAL,normalizePedal,pedalKey,pedalAction,readingTarget} from '../public/pedal.js';
assert.equal(pedalAction({code:'PageDown',key:'PageDown'},DEFAULT_PEDAL),'pageDown');
assert.equal(pedalAction({code:'PageUp',key:'PageUp'},DEFAULT_PEDAL),'pageUp');
assert.equal(pedalAction({code:'PageDown',key:'PageDown',repeat:true},DEFAULT_PEDAL),null);
assert.equal(pedalAction({code:'PageDown',key:'PageDown',ctrlKey:true},DEFAULT_PEDAL),null);
assert.equal(pedalAction({code:'PageDown',key:'PageDown'},{...DEFAULT_PEDAL,enabled:false}),null);
assert.equal(pedalKey({code:'Unidentified',key:'ArrowDown'}),'ArrowDown');
assert.equal(pedalKey({code:'NumpadEnter',key:'Enter'}),'Enter');
assert.equal(pedalKey({code:'Space',key:' '}),'Space');
assert.equal(pedalKey({code:'Escape',key:'Escape'}),'');
const custom=normalizePedal({enabled:true,left:{key:'ArrowUp',action:'previousSong'},right:{key:'ArrowDown',action:'toggleScroll'}});
assert.equal(pedalAction({code:'ArrowDown'},custom),'toggleScroll');
assert.equal(pedalAction({code:'ArrowUp'},custom),'previousSong');
assert.equal(normalizePedal({left:{key:'KeyA',action:'unknown'}}).left.action,'pageUp');
assert.equal(readingTarget(0,1000,4000,1),850);assert.equal(readingTarget(0,1000,4000,-1),0);assert.equal(readingTarget(2900,1000,4000,1),3000);assert.equal(readingTarget(0,1000,600,1),0);
console.log('PASS: default and learned pedal keys, functions, disabled/repeat/modifier guards, keyboard fallbacks and reading movement bounds.');
